/** The shape without one file: the canary that a shape with no README still derives and renders. */
export function without(shape: SyntheticShape, path: string, cited: string): SyntheticShape {
  const rest = new Map(shape.files);
  rest.delete(path);
  return { ...shape, name: `${shape.name}-without-${path}`, files: rest, cited };
}

/** The shape's tree listing as the dossier reader lists a pinned tree: path and mode, sorted by path. */
export function treeListing(shape: SyntheticShape): { readonly path: string; readonly mode: string }[] {
  return [...shape.files].map(([path, file]) => ({ path, mode: file.mode ?? '100644' })).sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

/** The canned operator-agent draft for a shape, citing its one file, as the render adapter would hand it to the renderer. */
export function shapeInput(shape: SyntheticShape): { readonly local: LocalRenderInput; readonly sources: readonly GenerationSource[] } {
  const body = shape.files.get(shape.cited)!.body;
  const base = { repositoryId: shape.repositoryId, revision: REVISION, path: shape.cited, objectId: gitBlobObjectId(body) };
  const source: GenerationSource = { ...base, sourceId: `src-${shape.name.replace(/[^a-z]/gu, '').slice(0, 12).padEnd(12, 'x')}0123456789ab`, evaluationId: `synthetic-evaluation:${shape.name}`,
    classificationBasis: 'body', exclusion: { excluded: false }, body,
    spans: [{ anchorId: generationAnchorId(base, 0, Buffer.byteLength(body)), start: 0, end: Buffer.byteLength(body), text: body }] };
  const anchor: EvidenceAnchor = { targetClass: 'evidence-artifact-identifier-with-integrity-digest', identifier: source.objectId!, algorithm: 'sha1',
    fragment: null, targetState: REVISION, pathLabel: source.path };
  const claim = (text: string) => ({ marking: 'inferred' as const, unknownReason: null, basis: 'fixture', executions: [], segments: [{ kind: 'prose' as const, text }] });
  const { nodes, edges, skip } = shape.diagram;
  const nodeId = (i: number) => `node-${i}`;
  return {
    sources: [source],
    local: {
      citationLines: new Map([['introduction', new Map([[source.sourceId, 'line 1']])]]),
      draft: {
        title: `The ${shape.name} dossier`,
        introduction: { id: 'introduction', text: 'intro', sourceIds: [source.sourceId] },
        sections: [{ id: 'what', title: 'What it does', disposition: { kind: 'produced', assetIds: [] }, paragraphs: [{ id: 'what-it-does', text: 'x', sourceIds: [source.sourceId], children: [] }] }],
        diagrams: [{
          id: 'main', sectionId: 'what', kind: 'flow', title: shape.diagram.title, relationship: shape.diagram.relationship, disposition: { kind: 'produced', assetIds: [] },
          nodes: nodes.map((label, i) => ({ id: nodeId(i), label, epistemic: 'inferred', sourceIds: [source.sourceId] })),
          edges: [...edges.map((label, i) => ({ id: `edge-${i}`, from: nodeId(i), to: nodeId(i + 1), label, epistemic: 'inferred', sourceIds: [source.sourceId] })),
            { id: 'edge-skip', from: nodeId(0), to: nodeId(2), label: skip, epistemic: 'inferred', sourceIds: [source.sourceId] }],
        }],
        deepDives: [],
        unresolved: [],
      } as unknown as LocalRenderInput['draft'],
      withheldTitle: `The ${shape.name} dossier, withheld`,
      draftLayer: { state: 'editorial-draft', ruling: 'fixture-ruling', inferenceProvenance: { modelIdentity: 'fixture-model', modelVersion: null, declaredBy: 'operator', label: 'Inferred' } },
      blocks: new Map<string, unknown>([['introduction', claim(`What ${shape.name} is for.`)], ['what-it-does', claim('What it does, in one sentence.')]]) as LocalRenderInput['blocks'],
      glossary: [],
      disclosure: [{ id: 'disclosure/fixture', text: 'How it was made.', label: null }],
      sourceAnchors: new Map([[source.sourceId, anchor]]),
      pages: [],
      reviewStatus: [{ id: 'review-status/fixture', text: 'Unreviewed.', label: 'Unknown' }],
    } as unknown as LocalRenderInput,
  };
}
